const QUERY = `import type { D1Client } from "@y-core/forge/storage/db";
import { sql } from "@y-core/forge/storage/db";
import type { Tables } from "./config/db/tables.ts";

export async function emails(db: D1Client): Promise<string[]> {
  const read = await db.query<Tables["users"]>(sql\`SELECT id, email FROM users\`);
  return read.ok ? read.data.map((row) => row.email) : [];
}
`;

const MISUSE = `import type { Tables } from "./config/db/tables.ts";

export function misuse(user: Tables["users"], post: Tables["posts"]): [number, string] {
  const n: number = user.email;
  const s: string = post.body;
  return [n, s];
}
`;

interface Step {
  readonly code: number;
  readonly stdout: string;
  readonly stderr: string;
}

function run(command: string, args: string[], cwd = FORGE): Promise<Step> {
  const child = spawn(command, args, { cwd });
  let stdout = "";
  let stderr = "";
  child.stdout.on("data", (chunk: Buffer) => (stdout += chunk.toString("utf-8")));
  child.stderr.on("data", (chunk: Buffer) => (stderr += chunk.toString("utf-8")));
  return new Promise((resolve) => child.on("close", (code) => resolve({ code: code ?? 1, stdout, stderr })));
}

const forgeDb = (root: string, args: string[]): Promise<Step> => run("bun", ["run", BIN, "db", ...args, "--root", root]);

function writeTsconfig(root: string, files: readonly string[]): string {
  const consumer = JSON.parse(readFileSync(join(CONSUMER, "tsconfig.json"), "utf-8")) as { compilerOptions: Record<string, unknown> };
  const compilerOptions = {
    ...consumer.compilerOptions,
    allowImportingTsExtensions: true,
    paths: { "@y-core/forge/*": [join(FORGE, "src", "*", "mod.ts"), join(FORGE, "src", "*")] },
  };
  const path = join(root, "tsconfig.json");
  writeFileSync(path, JSON.stringify({ compilerOptions, files: [...files, join(CONSUMER, "workerd-globals.d.ts")] }));
  return path;
}

const typecheck = (tsconfig: string): Promise<Step> => run("bun", ["check", "--no-script", "--no-pretty", "-p", tsconfig], root);

test.describe.configure({ mode: "serial", timeout: 240_000 });

let root = "";
let schema = "";
let tables = "";

test.beforeAll(() => {
  root = mkdtempSync(join(tmpdir(), "forge-db-types-"));
  schema = join(root, "schema.sql");
  tables = join(root, "config", "db", "tables.ts");
  cpSync(join(FIXTURE, "wrangler.jsonc"), join(root, "wrangler.jsonc"));
  mkdirSync(join(root, "config"));
  writeFileSync(join(root, "config", "db.config.ts"), `export default { schemas: ["schema.sql"] };\n`);
  writeFileSync(schema, `${readFileSync(join(FIXTURE, "cases", "add-table", "after.sql"), "utf-8")}${FILES_DDL}`);
});

test.afterAll(() => {
  rmSync(root, { recursive: true, force: true });
});

test("writes one row interface per table, typed as local D1 reports each column", async () => {
  const written = await forgeDb(root, ["types"]);

  expect(written.code, written.stderr).toBe(0);
  expect(readFileSync(tables, "utf-8")).toBe(EXPECTED);
});

test("types a query's rows by the generated interfaces, and refuses a row used against its column's type", async () => {
  writeFileSync(join(root, "query.ts"), QUERY);
  const clean = await typecheck(writeTsconfig(root, ["query.ts", "config/db/tables.ts"]));
  expect(clean.code, `${clean.stdout}${clean.stderr}`).toBe(0);

  writeFileSync(join(root, "misuse.ts"), MISUSE);
  const refused = await typecheck(writeTsconfig(root, ["query.ts", "misuse.ts", "config/db/tables.ts"]));
  const output = `${refused.stdout}${refused.stderr}`;
  expect(refused.code).not.toBe(0);
  expect(output.split("\n").filter((line) => line.startsWith("misuse.ts") && line.includes("TS2322"))).toHaveLength(2);
});

test("types a CURRENT_TIMESTAMP default as local D1 reads it back, which is text in a DATETIME column", async () => {
  mkdirSync(join(root, "migrations"));
  writeFileSync(join(root, "migrations", "0001_files.sql"), FILES_DDL);
  const d1 = await openTestD1({ root, migrations: "migrations" });
  let stamped: unknown;
  try {
    await d1.binding.prepare("INSERT INTO files (key, body) VALUES ('k', x'00')").run();
    [{ stamped }] = (await d1.rows("SELECT stamped FROM files")) as [{ stamped: unknown }];
  } finally {
    await d1.dispose();
  }
  expect(typeof stamped).toBe("string");

  const readBack = `import type { Tables } from "./config/db/tables.ts";\n\nexport const stamped: Tables["files"]["stamped"] = ${JSON.stringify(stamped)};\n`;
  writeFileSync(join(root, "stamped.ts"), readBack);
  const checked = await typecheck(writeTsconfig(root, ["stamped.ts", "config/db/tables.ts"]));
  expect(checked.code, `${checked.stdout}${checked.stderr}`).toBe(0);
});

test("fails --check on a schema edit or a missing file, leaving the file alone until forge db types runs", async () => {
  expect((await forgeDb(root, ["types", "--check"])).code).toBe(0);

  const before = readFileSync(tables, "utf-8");
  writeFileSync(schema, readFileSync(schema, "utf-8").replace("email TEXT NOT NULL)", "email TEXT NOT NULL, nickname TEXT)"));
  const stale = await forgeDb(root, ["types", "--check"]);
  expect(stale.code).toBe(1);
  expect(stale.stdout).toContain("is not what");
  expect(readFileSync(tables, "utf-8")).toBe(before);

  expect((await forgeDb(root, ["types"])).code).toBe(0);
  expect((await forgeDb(root, ["types", "--check"])).code).toBe(0);

  rmSync(tables);
  const absent = await forgeDb(root, ["types", "--check"]);
  expect(absent.code).toBe(1);
  expect(absent.stdout).toContain("does not exist");
});

import { describe, expect, it } from "bun:test";

import { CliError } from "../../cli/errors";
import { columnRowType, emitRowTypes, rowInterfaceName } from "./row-types";
import type { SchemaColumn, SchemaModel, SchemaTable } from "./types";

const HEADER = "/** GENERATED by `forge db types` from the declared schemas — do not edit; run `forge db types` again. */";

function column(name: string, type: string, over: Partial<SchemaColumn> = {}): SchemaColumn {
  return { name, type, notnull: false, defaultExpr: null, pk: 0, hidden: 0, definition: "", definitionSource: "", ...over };
}

function table(name: string, columns: readonly SchemaColumn[], over: Partial<SchemaTable> = {}): SchemaTable {
  return { name, columns, constraints: [], strict: false, withoutRowid: false, foreignKeys: [], sql: "", ...over };
}

function model(tables: readonly SchemaTable[]): SchemaModel {
  return { tables, indexes: [], triggers: [], views: [] };
}

const USERS = table("users", [column("id", "INTEGER", { pk: 1 }), column("email", "TEXT", { notnull: true })], { strict: true });
const POSTS = table("posts", [column("id", "INTEGER", { pk: 1 }), column("user_id", "INTEGER", { notnull: true }), column("body", "TEXT")], {
  strict: true,
});

const USERS_POSTS_TEXT = `${HEADER}

export interface PostsRow {
  id: number;
  user_id: number;
  body: string | null;
}

export interface UsersRow {
  id: number;
  email: string;
}

export interface Tables {
  posts: PostsRow;
  users: UsersRow;
}
`;

const typeOf = (type: string, over: Partial<SchemaTable> = {}): string => columnRowType(table("t", [], over), column("c", type, { notnull: true }));

describe("columnRowType()", () => {
  it("reads an INT affinity as a number", () => {
    expect(["INT", "INTEGER", "BIGINT", "UNSIGNED BIG INT"].map((type) => typeOf(type))).toEqual(["number", "number", "number", "number"]);
  });

  it("reads a TEXT affinity as a string, whatever the case it was declared in", () => {
    expect(["VARCHAR(255)", "NCHAR(55)", "TEXT", "CLOB", "text"].map((type) => typeOf(type))).toEqual([
      "string",
      "string",
      "string",
      "string",
      "string",
    ]);
  });

  it("reads a BLOB as the byte array D1 returns", () => {
    expect(typeOf("BLOB")).toBe("number[]");
  });

  it("reads a column with no declared type as any value", () => {
    expect(typeOf("")).toBe("number | string | number[]");
  });

  it("reads REAL and NUMERIC affinities as a number or the text SQLite keeps when it is not one, on a plain table", () => {
    const types = ["REAL", "DOUBLE PRECISION", "FLOAT", "NUMERIC", "DECIMAL(10,5)", "BOOLEAN", "DATE", "DATETIME"];
    expect(new Set(types.map((type) => typeOf(type)))).toEqual(new Set(["number | string"]));
  });

  it("reads REAL as a number on a STRICT table, which refuses text there", () => {
    expect(typeOf("REAL", { strict: true })).toBe("number");
  });

  it("applies SQLite's affinity precedence", () => {
    expect([typeOf("CHARINT"), typeOf("FLOATING POINT"), typeOf("BLOBTEXT")]).toEqual(["number", "number", "string"]);
    expect(typeOf("DOUBLE")).toBe("number | string");
  });

  it("reads ANY as any value on a STRICT table and by NUMERIC affinity on a plain one", () => {
    expect([typeOf("ANY", { strict: true }), typeOf("ANY")]).toEqual(["number | string | number[]", "number | string"]);
  });

  it("adds null to a column that may hold one and not to a NOT NULL column", () => {
    const t = table("t", []);
    expect([columnRowType(t, column("a", "TEXT", { notnull: true })), columnRowType(t, column("b", "TEXT"))]).toEqual(["string", "string | null"]);
  });

  it("reads the rowid alias as never null", () => {
    const id = column("id", "INTEGER", { pk: 1 });
    expect(columnRowType(table("t", [id, column("v", "TEXT")]), id)).toBe("number");
  });

  it("reads an INT PRIMARY KEY as nullable, since it is not the rowid alias", () => {
    const id = column("id", "INT", { pk: 1 });
    expect(columnRowType(table("t", [id]), id)).toBe("number | null");
  });

  it("reads an INTEGER column of a composite key as nullable", () => {
    const a = column("a", "INTEGER", { pk: 1 });
    expect(columnRowType(table("t", [a, column("b", "INTEGER", { pk: 2 })]), a)).toBe("number | null");
  });

  it("reads an INTEGER PRIMARY KEY of a WITHOUT ROWID table by its notnull alone", () => {
    const id = column("id", "INTEGER", { pk: 1 });
    expect(columnRowType(table("t", [id], { withoutRowid: true }), id)).toBe("number | null");
  });
});

describe("rowInterfaceName()", () => {
  it("PascalCases each letter-and-digit word and appends Row", () => {
    expect(["users", "user_posts", "order items", "2fa_codes", "café", "tables"].map(rowInterfaceName)).toEqual([
      "UsersRow",
      "UserPostsRow",
      "OrderItemsRow",
      "Table2faCodesRow",
      "CaféRow",
      "TablesRow",
    ]);
  });

  it("refuses a table name with no letter or digit, naming it", () => {
    expect(() => rowInterfaceName("---")).toThrow(CliError);
    expect(() => rowInterfaceName("---")).toThrow('"---"');
  });
});

describe("emitRowTypes()", () => {
  it("emits one interface per table and the Tables map, in name order", () => {
    expect(emitRowTypes(model([USERS, POSTS]))).toBe(USERS_POSTS_TEXT);
  });

  it("orders tables by code point rather than by UTF-16 unit", () => {
    const text = emitRowTypes(model([table("\u{10400}", [column("a", "TEXT")]), table("ａ", [column("a", "TEXT")])]));
    expect(text).toEndWith("export interface Tables {\n  ａ: ＡRow;\n  \u{10400}: \u{10400}Row;\n}\n");
  });

  it("keeps the columns in declared order and includes generated ones", () => {
    const text = emitRowTypes(
      model([
        table("t", [
          column("z", "TEXT", { notnull: true }),
          column("a", "INTEGER", { notnull: true }),
          column("virtual_total", "INTEGER", { hidden: 2 }),
          column("stored_total", "INTEGER", { hidden: 3 }),
        ]),
      ]),
    );
    expect(text).toContain(
      "export interface TRow {\n  z: string;\n  a: number;\n  virtual_total: number | null;\n  stored_total: number | null;\n}\n",
    );
  });

  it("quotes a key only where it is not an identifier", () => {
    const text = emitRowTypes(
      model([table("t", [column("display name", "TEXT"), column("2fa", "TEXT"), column("$x", "TEXT"), column("café", "TEXT")])]),
    );
    expect(text).toContain('  "display name": string | null;\n  "2fa": string | null;\n  $x: string | null;\n  café: string | null;\n');
  });

  it("refuses two tables that name one row interface, naming both and the interface", () => {
    const clash = model([table("user_posts", []), table("userPosts", [])]);
    expect(() => emitRowTypes(clash)).toThrow(CliError);
    expect(() => emitRowTypes(clash)).toThrow("tables userPosts and user_posts both name the row interface UserPostsRow — rename one");
  });

  it("emits an empty Tables map for a model with no tables", () => {
    expect(emitRowTypes(model([]))).toBe(`${HEADER}\n\nexport interface Tables extends Record<never, never> {}\n`);
  });
});

import { compareCodePoints } from "../../../storage/db/schema";
import { CliError } from "../../cli/errors";
import type { SchemaColumn, SchemaModel, SchemaTable } from "./types";

const HEADER = "/** GENERATED by `forge db types` from the declared schemas — do not edit; run `forge db types` again. */";
const ANY_VALUE = "number | string | number[]";
const IDENTIFIER = /^[\p{ID_Start}$_][\p{ID_Continue}$\u200C\u200D]*$/u;
const ID_START = /^[\p{ID_Start}$_]/u;

const key = (name: string): string => (IDENTIFIER.test(name) ? name : JSON.stringify(name));

function columnBaseType(table: SchemaTable, declared: string): string {
  if (table.strict && declared === "ANY") return ANY_VALUE;
  if (declared.includes("INT")) return "number";
  if (["CHAR", "CLOB", "TEXT"].some((word) => declared.includes(word))) return "string";
  if (declared.includes("BLOB")) return "number[]";
  if (declared === "") return ANY_VALUE;
  return table.strict ? "number" : "number | string";
}

function capitaliseWord(word: string): string {
  const [first = "", ...rest] = [...word];
  return first.toUpperCase() + rest.join("");
}

function isRowidAlias(table: SchemaTable, column: SchemaColumn, declared: string): boolean {
  const keyColumns = table.columns.filter((candidate) => candidate.pk > 0).length;
  return !table.withoutRowid && column.pk === 1 && declared === "INTEGER" && keyColumns === 1;
}

/** The TypeScript type D1 reads one column back as, by SQLite's affinity precedence, with `| null` unless the column cannot hold one. @internal */
export function columnRowType(table: SchemaTable, column: SchemaColumn): string {
  const declared = column.type.toUpperCase();
  const base = columnBaseType(table, declared);
  return column.notnull || isRowidAlias(table, column, declared) ? base : `${base} | null`;
}

/** The row interface a table is emitted as: its letter-and-digit words in PascalCase, then `Row`. @internal */
export function rowInterfaceName(table: string): string {
  const words = table.split(/[^\p{L}\p{N}]+/u).filter((word) => word !== "");
  if (words.length === 0)
    throw new CliError("invalid-args", `table ${JSON.stringify(table)} has no letter or digit to name a row interface after — rename it`);
  const name = `${words.map(capitaliseWord).join("")}Row`;
  return ID_START.test(name) ? name : `Table${name}`;
}

/** The row-types module for a model: one interface per table and a `Tables` map, in code-point order. @internal */
export function emitRowTypes(model: SchemaModel): string {
  const tables = [...model.tables].sort((a, b) => compareCodePoints(a.name, b.name));
  const names = tables.map((table) => rowInterfaceName(table.name));
  const owners = new Map<string, string>();
  tables.forEach((table, index) => {
    const name = names[index] ?? "";
    const owner = owners.get(name);
    if (owner !== undefined)
      throw new CliError("invalid-args", `tables ${owner} and ${table.name} both name the row interface ${name} — rename one`);
    owners.set(name, table.name);
  });
  const interfaces = tables.flatMap((table, index) => [
    `export interface ${names[index]} {`,
    ...table.columns.map((column) => `  ${key(column.name)}: ${columnRowType(table, column)};`),
    "}",
    "",
  ]);
  const map =
    tables.length === 0
      ? ["export interface Tables extends Record<never, never> {}"]
      : ["export interface Tables {", ...tables.map((table, index) => `  ${key(table.name)}: ${names[index]};`), "}"];
  return `${[HEADER, "", ...interfaces, ...map].join("\n")}\n`;
}

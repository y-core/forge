import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join } from "node:path";
import type { ResolvedConfig } from "../types";
import { copyAssets } from "./copy";
import { buildCSS } from "./css";
import { buildCursors } from "./cursors";
import { buildFonts } from "./fonts";
import { buildIcons } from "./icons";
import { buildJS } from "./js";
import type { SpriteGroupResult } from "./sprites";
import { buildSprites } from "./sprites";

export interface BuildOptions {
  minify?: boolean;
  assetsPath?: string;
}

/** Runs every configured build step and writes the generated assets module; `minify` also enables content-hashed filenames. @public */
export async function buildAll(config: ResolvedConfig, opts?: BuildOptions): Promise<void> {
  const { publicDir, publicPrefix } = config.paths;
  const shouldHash = opts?.minify ?? false;
  mkdirSync(publicDir, { recursive: true });

  const manifest: Record<string, string> = {};
  let spriteGroups: Record<string, SpriteGroupResult> = {};
  let cursorBakes: Record<string, Record<string, string>> | undefined;

  const minifyOpts = opts?.minify !== undefined ? { minify: opts.minify } : {};

  for (const css of config.css) {
    const mapping = buildCSS(css, { outDir: publicDir, ...minifyOpts, hash: shouldHash });
    Object.assign(manifest, mapping);
  }

  copyAssets(config.copy, publicDir);

  if (Object.keys(config.sprites).length > 0) {
    const result = await buildSprites(config.sprites, publicDir, { hash: shouldHash });
    Object.assign(manifest, result.mapping);
    spriteGroups = result.groups;
  }

  if (config.fonts.downloads.length > 0) {
    await buildFonts(config.fonts, publicDir);
  }

  if (config.icons) {
    await buildIcons(config.icons);
  }

  if (config.cursors) {
    const cssKey = config.cursors.css ?? config.css[0]?.output;
    const resolvedCss = cssKey !== undefined ? (manifest[cssKey] ?? cssKey) : undefined;
    if (resolvedCss) {
      const cssText = readFileSync(join(publicDir, resolvedCss), "utf-8");
      cursorBakes = buildCursors(config.cursors, cssText);
    }
  }

  const outputPath = opts?.assetsPath ?? DEFAULT_ASSETS_PATH;
  // esbuild resolves `@assets` while bundling, so the module must exist before `buildJS`.
  await generateAssetsModule(manifest, spriteGroups, publicPrefix, outputPath, cursorBakes);

  Object.assign(manifest, await buildJS(config.js.bundles, { outDir: publicDir, ...minifyOpts, hash: shouldHash }));

  await generateAssetsModule(manifest, spriteGroups, publicPrefix, outputPath, cursorBakes);

  emitHeaders(publicDir, shouldHash);
}

const DEFAULT_ASSETS_PATH = ".forge/assets.ts";

const BUILD_HEADER = "// AUTO-GENERATED by @y-core/forge assets build — do not edit.";

const TYPES_HEADER = [
  "// AUTO-GENERATED by `forge-assets types` from assets.config.ts — do not edit.",
  "// TYPES ONLY: every path here is the unhashed logical name and every viewBox is empty.",
  "// Run `forge-assets build all` before serving — this artifact is for typecheck and tests.",
].join("\n");

function toConstName(key: string): string {
  return `${key.replace(/[^a-zA-Z0-9]+/g, "_").toUpperCase()}_META`;
}

function toPascalCase(key: string): string {
  return key
    .split(/[^a-zA-Z0-9]+/)
    .map((seg) => (seg ? seg.charAt(0).toUpperCase() + seg.slice(1) : ""))
    .join("");
}

async function generateAssetsModule(
  manifest: Record<string, string>,
  spriteGroups: Record<string, SpriteGroupResult>,
  publicPrefix: string,
  outputPath: string,
  cursorBakes?: Record<string, Record<string, string>>,
  header: string = BUILD_HEADER,
): Promise<void> {
  const dataEntries = Object.entries(manifest)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n");

  const hasSprites = Object.keys(spriteGroups).length > 0;

  let content: string;

  if (hasSprites) {
    const groupBlocks = Object.entries(spriteGroups)
      .map(([key, group]) => {
        const constName = toConstName(key);
        const exportName = `${toPascalCase(key)}Icon`;
        const metaEntries = Object.entries(group.meta)
          .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
          .join("\n");
        return `const ${constName} = {\n${metaEntries}\n} as const;\n\nexport const ${exportName} = createIcon(assets.path(${JSON.stringify(group.spriteKey)}), ${constName}, ${JSON.stringify(group.prefix)});`;
      })
      .join("\n\n");

    content = `${header}
import { createManifest } from "@y-core/forge/assets/manifest";
import { createIcon } from "@y-core/forge/ui/core";

const DATA: Record<string, string> = {
${dataEntries}
};

export const assets = createManifest(DATA, ${JSON.stringify(publicPrefix)});

${groupBlocks}
`;
  } else {
    content = `${header}
import { createManifest } from "@y-core/forge/assets/manifest";

const DATA: Record<string, string> = {
${dataEntries}
};

export const assets = createManifest(DATA, ${JSON.stringify(publicPrefix)});
`;
  }

  if (cursorBakes && Object.keys(cursorBakes).length > 0) {
    const cursorEntries = Object.entries(cursorBakes)
      .map(([cursor, themes]) => {
        const themeEntries = Object.entries(themes)
          .map(([theme, value]) => `    ${JSON.stringify(theme)}: ${JSON.stringify(value)},`)
          .join("\n");
        return `  ${JSON.stringify(cursor)}: {\n${themeEntries}\n  },`;
      })
      .join("\n");
    content += `\nexport const CURSOR_BAKES: Record<string, Record<string, string>> = {\n${cursorEntries}\n};\n`;
  }

  if (existsSync(outputPath) && readFileSync(outputPath, "utf-8") === content) return;
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, content);
}

/** Writes the generated assets module from `assets.config.ts` alone, with placeholder values. @public */
export async function generateAssetsTypes(config: ResolvedConfig, opts?: { assetsPath?: string }): Promise<void> {
  const manifest: Record<string, string> = {};

  for (const css of config.css) {
    manifest[css.output] = css.output;
  }

  const spriteGroups: Record<string, SpriteGroupResult> = {};
  for (const [key, group] of Object.entries(config.sprites)) {
    manifest[group.target] = group.target;

    const prefix = group.prefix ?? "icon-";
    const meta: Record<string, string> = {};
    for (const source of group.sources) {
      for (const rawEntry of source.files) {
        const symbolKey = typeof rawEntry === "string" ? basename(rawEntry, ".svg") : rawEntry.key;
        meta[`${prefix}${symbolKey}`] = "";
      }
    }
    spriteGroups[key] = { spriteKey: group.target, meta, prefix };
  }

  for (const bundle of config.js.bundles) {
    const logicalName = `${bundle.outdir}/${basename(bundle.entry, extname(bundle.entry))}.js`;
    manifest[logicalName] = logicalName;
  }

  let cursorBakes: Record<string, Record<string, string>> | undefined;
  const cursors = config.cursors;
  if (cursors) {
    cursorBakes = {};
    const themes = Object.keys(cursors.themes);
    for (const source of cursors.sources) {
      for (const rawEntry of source.files) {
        const cursorKey = typeof rawEntry === "string" ? rawEntry.replace(/\.svg$/, "") : rawEntry.key;
        const perTheme: Record<string, string> = {};
        for (const theme of themes) perTheme[theme] = "";
        cursorBakes[cursorKey] = perTheme;
      }
    }
  }

  await generateAssetsModule(manifest, spriteGroups, config.paths.publicPrefix, opts?.assetsPath ?? DEFAULT_ASSETS_PATH, cursorBakes, TYPES_HEADER);
}

function emitHeaders(publicDir: string, hashed: boolean): void {
  const headersPath = join(dirname(publicDir), "_headers");
  const cacheControl = hashed ? "public, max-age=31536000, immutable" : "no-cache";
  const content = `/assets/*\n  Cache-Control: ${cacheControl}\n`;
  writeFileSync(headersPath, content);
}
